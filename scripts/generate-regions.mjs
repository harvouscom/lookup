#!/usr/bin/env node
// Generate worker/src/regions.generated.ts from the HMC repo's region table and countries route.
// Usage: node scripts/generate-regions.mjs <path to heresmychurch checkout> <countries.json>
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const [repo, countriesFile] = process.argv.slice(2);
const show = (p) => execFileSync("git", ["-C", repo, "show", `origin/main:${p}`], { encoding: "utf8", maxBuffer: 1e8 });
const intlSrc = show("supabase/functions/make-server-283d8046/regions-intl.ts");
const intl = JSON.parse(intlSrc.slice(intlSrc.indexOf("={") + 1, intlSrc.lastIndexOf("}") + 1).trim().replace(/;$/, ""));
const app = show("supabase/functions/make-server-283d8046/app.ts");
const us = JSON.parse(app.match(/const S:\[string,string,number,number\]\[\]=(\[\[.*?\]\]);/s)[1]);
const countries = {};
for (const c of JSON.parse(readFileSync(countriesFile, "utf8")).countries) countries[c.code] = c.name;

const regions = {};
for (const [a, n, la, lo] of us) regions[a] = { cc: "US", n, la, lo };
regions.DC ??= { cc: "US", n: "District of Columbia", la: 38.9, lo: -77.03 };
for (const [a, r] of Object.entries(intl)) regions[a] ??= { cc: r.cc, n: r.n, la: r.la, lo: r.lo };

const sorted = Object.fromEntries(Object.entries(regions).sort(([a], [b]) => (a < b ? -1 : 1)));
writeFileSync("worker/src/regions.generated.ts",
  `// GENERATED by scripts/generate-regions.mjs. Do not edit by hand.\n` +
  `export interface Region { cc: string; n: string; la: number; lo: number }\n` +
  `export const REGIONS: Record<string, Region> = ${JSON.stringify(sorted)};\n` +
  `export const COUNTRIES: Record<string, string> = ${JSON.stringify(countries)};\n`);
console.log(Object.keys(sorted).length, "regions", Object.keys(countries).length, "countries");
